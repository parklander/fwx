"""Weekly report: what FWX's users did, what they said and what broke, for the Saturday review.

Every Saturday at REPORT_HOUR (local) the server writes a Markdown report of the past 7 days to
data/reports/YYYY-MM-DD.md and, when FW_REPORT_REPO and FW_REPORT_TOKEN are set, puts it in that GitHub repo
as weekly/YYYY-MM-DD.md and weekly/latest.md through the GitHub contents API (no git needed on the server).
The repo must be private: the report quotes user feedback. IP addresses are not included, only counts by
kind of network.

FW_REPORT_REPO   owner/name, e.g. parklander/fwx-reports (private)
FW_REPORT_TOKEN  a fine-grained GitHub token with Contents: read and write on that one repo
"""
import base64
import json
import logging
import os
import threading
from collections import Counter, deque
from datetime import datetime, timedelta, timezone
from pathlib import Path

import requests

log = logging.getLogger("fwx.report")

REPORT_WEEKDAY = 5  # Saturday
REPORT_HOUR = 6
PAGE_NAMES = {"main": "Map", "beta": "Beta", "range": "Alert panel", "about": "About"}


# ---- warnings and errors the server logged, counted, for "what broke" -----------------------------------------
class LogTally(logging.Handler):
    """Keeps the last few thousand WARNING+ log records (time, logger, first line), to count them by kind."""

    def __init__(self, keep=5000):
        super().__init__(level=logging.WARNING)
        self.recs = deque(maxlen=keep)

    def emit(self, record):
        try:
            msg = record.getMessage().splitlines()[0][:160]
        except Exception:
            msg = str(record.msg)[:160]
        self.recs.append((datetime.now(timezone.utc).isoformat(timespec="seconds"), record.levelname, record.name, msg,
                          bool(record.exc_info)))

    def since(self, iso):
        out = Counter()
        for t, lvl, name, msg, exc in list(self.recs):
            if t >= iso:
                out[(lvl, name, _shape(msg), exc)] += 1
        return out


def _shape(msg):
    """Group messages that differ only in numbers or quoted values."""
    import re
    return re.sub(r"\d+(\.\d+)?", "#", re.sub(r"'[^']*'|\"[^\"]*\"", "'…'", msg))[:120]


def _net(ip):
    return "Government of Canada network" if ip.startswith(("205.192.", "205.193.", "205.194.", "205.195.")) else "other networks"


def build(usage_log, health_events, tally, areas, days=7, now=None):
    now = now or datetime.now(timezone.utc)
    since = (now - timedelta(days=days)).isoformat(timespec="seconds")
    U = usage_log.summary(days)
    names = {a["id"]: a["name"] for a in areas}
    L = []
    w = L.append
    w(f"# FWX weekly report: {U['from']} to {now.date()}")
    w("")
    w("Generated by the FWX server for the Saturday review. Counts only, no IP addresses. Feedback is quoted as sent.")
    w("")
    # ---- headline numbers
    t = U["totals"]
    w("## Use")
    w(f"- {t['views']} page views from {t['ips']} different addresses "
      f"({', '.join(f'{n} on the {k}' for k, n in Counter(_net(x['ip']) for x in U['by_ip']).most_common())}).")
    ret = U.get("returning", {})
    w(f"- Coming back: {ret.get('1 day', 0)} addresses on 1 day, {ret.get('2 days', 0)} on 2, {ret.get('3 days', 0)} on 3, "
      f"{ret.get('4+ days', 0)} on 4 or more.")
    if U["by_day"]:
        w("- By day: " + ", ".join(f"{d['day'][5:]} {d['ips']}" for d in U["by_day"]) + " (different addresses).")
    if U["by_page"]:
        w("- Pages: " + ", ".join(f"{PAGE_NAMES.get(k, k)} {v}" for k, v in U["by_page"].items()) + " views.")
    devs = Counter(x["ua"] for x in U["by_ip"] if x.get("ua"))
    if devs:
        w("- Devices: " + ", ".join(f"{k} {v}" for k, v in devs.most_common(6)) + " (addresses).")
    w("")
    w("### Visits")
    if U.get("visits"):
        for pg, v in U["visits"].items():
            w(f"- {PAGE_NAMES.get(pg, pg)}: {v['visits']} visits, median {v['median_s']} s, 3 in 4 under {v['p75_s']} s; "
              f"{v['glance']} glances (<30 s), {v['check']} checks (<3 min), {v['work']} working sessions; {v['hours']} h on screen.")
    else:
        w("- No timed visits.")
    w("")
    w("### Bases looked at")
    for b in U["by_base"][:15]:
        w(f"- {names.get(b['aoi'], b['aoi'])}: {b['views']} views from {b['ips']} addresses" + (f", {b['pdf']} PDFs" if b["pdf"] else ""))
    if not U["by_base"]:
        w("- None.")
    w("")
    w("### Features used (share of visits that used it at least once)")
    acts = [a for a in U.get("actions", []) if a["action"] != "feedback_dismissed"]
    for a in acts:
        w(f"- {PAGE_NAMES.get(a['page'], a['page'])}: {a['action'].replace('_', ' ')} {round(a['share'] * 100)}% ({a['visits']} visits)")
    if not acts:
        w("- None logged.")
    if U.get("tabs"):
        w("- Forecast panel tabs opened: " + ", ".join(f"{k} {v}" for k, v in U["tabs"].items()))
    dismissed = next((a["visits"] for a in U.get("actions", []) if a["action"] == "feedback_dismissed"), 0)
    w("")
    w(f"### Map layers (share of {U['main_ipdays']} map visits, one per address per day)")
    for l in U["layers"][:20]:
        w(f"- {l['layer']}: {round(l['share'] * 100)}%")
    if not U["layers"]:
        w("- None logged.")
    w("")
    # ---- feedback
    fv = U.get("feedback_votes", {})
    w(f"## Feedback: {fv.get('up', 0)} 👍, {fv.get('down', 0)} 👎" + (f", {dismissed} closed without answering" if dismissed else ""))
    fb = [f for f in U.get("feedback", []) if f.get("t", "") >= since]
    for f in fb:
        where = f"{PAGE_NAMES.get(f.get('page'), f.get('page'))}" + (f", {names.get(f['aoi'], f['aoi'])}" if f.get("aoi") else "")
        w(f"- {'👍' if f.get('vote') == 'up' else '👎'} {f['t'][:16].replace('T', ' ')} UTC ({where}): "
          + (f"\"{f['text']}\"" if f.get("text") else "no comment"))
    if not fb:
        w("- None this week.")
    w("")
    # ---- what broke
    w("## Data feed problems")
    ev = [e for e in health_events if e.get("t", "") >= since]
    for e in ev:
        w(f"- {e['t'][:16].replace('T', ' ')} UTC · {e['kind']}: {e['name']}: {e['msg']}")
    if not ev:
        w("- No feed went down long enough to notify (two failed checks in a row).")
    w("")
    w("## Warnings and errors the server logged")
    counts = tally.since(since) if tally else Counter()
    if counts:
        w("Grouped by message; numbers replaced with #. Counts since the last restart if that was within the week.")
        for (lvl, name, msg, exc), n in counts.most_common(25):
            w(f"- {n}× {lvl} {name}: {msg}" + (" (with traceback)" if exc else ""))
    else:
        w("- None.")
    w("")
    return "\n".join(L)


def publish(text, day):
    """Put the report in FW_REPORT_REPO (weekly/<day>.md and weekly/latest.md). Returns a status string."""
    repo, token = os.environ.get("FW_REPORT_REPO", ""), os.environ.get("FW_REPORT_TOKEN", "")
    if not repo or not token:
        return "not published: FW_REPORT_REPO / FW_REPORT_TOKEN not set"
    h = {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
    info = requests.get(f"https://api.github.com/repos/{repo}", headers=h, timeout=30)
    if info.status_code != 200:
        return f"not published: can't open {repo} ({info.status_code})"
    if not info.json().get("private"):
        return f"not published: {repo} is public; the report quotes user feedback, so the repo must be private"
    out = []
    for path in (f"weekly/{day}.md", "weekly/latest.md"):
        url = f"https://api.github.com/repos/{repo}/contents/{path}"
        cur = requests.get(url, headers=h, timeout=30)
        body = {"message": f"FWX weekly report {day}", "content": base64.b64encode(text.encode()).decode()}
        if cur.status_code == 200:
            body["sha"] = cur.json()["sha"]
        r = requests.put(url, headers=h, json=body, timeout=30)
        out.append(f"{path}: {r.status_code}")
        if r.status_code not in (200, 201):
            log.warning("report publish %s failed: %s %s", path, r.status_code, r.text[:200])
    return "published to " + repo + " (" + ", ".join(out) + ")"


class Weekly:
    def __init__(self, data_dir, tz, build_fn):
        self.dir = Path(data_dir) / "reports"
        self.dir.mkdir(parents=True, exist_ok=True)
        self.state = Path(data_dir) / "report_state.json"
        self.tz, self.build_fn = tz, build_fn
        self.lock = threading.Lock()

    def last(self):
        try:
            return json.loads(self.state.read_text())
        except Exception:
            return {}

    def make(self, publish_it=True):
        day = datetime.now(self.tz).date().isoformat()
        text = self.build_fn()
        with self.lock:
            (self.dir / f"{day}.md").write_text(text, encoding="utf-8")
            status = publish(text, day) if publish_it else "not published (preview)"
            if publish_it:
                self.state.write_text(json.dumps({"day": day, "status": status,
                                                  "at": datetime.now(timezone.utc).isoformat(timespec="seconds")}))
        log.info("weekly report %s: %s", day, status)
        return day, text, status

    def loop(self, stop):
        while not stop.is_set():
            now = datetime.now(self.tz)
            if now.weekday() == REPORT_WEEKDAY and now.hour >= REPORT_HOUR and self.last().get("day") != now.date().isoformat():
                try:
                    self.make()
                except Exception:
                    log.exception("weekly report failed")
            stop.wait(15 * 60)
